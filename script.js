function getNearestCity(lat, lon) {
  let closest = KOREAN_CITIES[0];
  let minDistance = Infinity;
  for (const city of KOREAN_CITIES) {
    const d = Math.hypot(city.lat - lat, city.lon - lon);
    if (d < minDistance) {
      minDistance = d;
      closest = city;
    }
  }
  return minDistance < 1.6 ? closest.name : "내 위치";
}

